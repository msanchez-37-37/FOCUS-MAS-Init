-- ============================================================
-- SECTION 7: Data migration - Combining Approved status for Objectives
-- ============================================================

Print '*** Section 7: Propagating APPROVED_STATUS from OBJECTIVE to OBJECTIVE_IMPL ***'
go

DECLARE @PK_OBJ_ID NUMERIC(12,0)
DECLARE @STATUS INT

DECLARE OBJ_CURSOR CURSOR FOR
    SELECT PK_OBJ_ID, APPROVED_STATUS
    FROM dbo.OBJECTIVE
    WHERE APPROVED_STATUS IS NOT NULL

OPEN OBJ_CURSOR
FETCH NEXT FROM OBJ_CURSOR INTO @PK_OBJ_ID, @STATUS

WHILE @@FETCH_STATUS = 0
BEGIN
    UPDATE dbo.OBJECTIVE_IMPL
    SET APPROVED_STATUS = @STATUS
    WHERE FK_OBJ_ID = @PK_OBJ_ID

    FETCH NEXT FROM OBJ_CURSOR INTO @PK_OBJ_ID, @STATUS
END

CLOSE OBJ_CURSOR
DEALLOCATE OBJ_CURSOR
go

