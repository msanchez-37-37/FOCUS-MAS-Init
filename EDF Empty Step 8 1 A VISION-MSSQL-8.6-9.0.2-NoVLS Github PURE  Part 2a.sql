Print '*** Section 2: Renaming PROGRAM_STATIC_EXAM default constraint ***'
go

IF NOT EXISTS (SELECT * FROM sys.objects WHERE name = 'DF_PROG_STATIC_EXAM_USED_IN_LS' AND type = 'D')
BEGIN
    DECLARE @ConstraintName NVARCHAR(200);
    SELECT @ConstraintName = dc.name
    FROM sys.default_constraints dc
    JOIN sys.columns c ON dc.parent_object_id = c.object_id AND dc.parent_column_id = c.column_id
    JOIN sys.tables t ON c.object_id = t.object_id
    WHERE t.name = 'PROGRAM_STATIC_EXAM' AND c.name = 'USED_IN_LS';

    IF @ConstraintName IS NOT NULL
        EXEC sp_rename @ConstraintName, 'DF_PROG_STATIC_EXAM_USED_IN_LS', 'OBJECT';
END
GO

